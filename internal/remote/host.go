// Package remote manages the remote herdr servers seshagy can switch to: the
// generated ssh config that gives every configured host a stable alias,
// discovery of hosts already defined in ~/.ssh/config, and the `seshagy run`
// launcher that attaches a local herdr client to one of them (or back to the
// local server).
package remote

import (
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/lmilojevicc/seshagy/internal/xdg"
)

// Transport values accepted for a configured host.
const (
	TransportSSH  = "ssh"
	TransportIroh = "iroh"
)

// generatedAliasPrefix namespaces the ssh aliases seshagy generates, so
// discovery can tell them apart from the user's own Host entries.
const generatedAliasPrefix = "seshagy-"

// sshConfigHeader is the first line of the generated ssh config.
const sshConfigHeader = "# Generated by seshagy — do not edit; " +
	"edit ~/.config/seshagy/config.toml [[hosts]] instead"

// Host is a herdr server seshagy can attach to. Configured hosts (from
// config.toml [[hosts]]) are rendered into the generated ssh config under the
// `seshagy-<name>` alias; discovered hosts come straight from the user's
// ~/.ssh/config and are used as-is.
type Host struct {
	Name         string
	Target       string
	Transport    string
	ProxyCommand string
	Session      string
	// Keybindings is the herdr --remote-keybindings value for this host
	// (KeybindingsLocal or KeybindingsServer); empty leaves herdr's default.
	Keybindings   string
	FromSSHConfig bool
}

// Keybinding modes accepted by `herdr --remote-keybindings`: local keeps the
// local client's keymap, server uses the remote server's.
const (
	KeybindingsLocal  = "local"
	KeybindingsServer = "server"
)

// LaunchTarget is the launcher target that attaches to this host. An empty
// session falls back to the host's configured one.
func (h Host) LaunchTarget(session string) Target {
	if session == "" {
		session = h.Session
	}
	return Target{Alias: h.Alias(), Session: session, Keybindings: h.Keybindings}
}

// Alias is the ssh alias handed to `herdr --remote`. Discovered hosts keep
// their own Host pattern because the user's config already knows it; configured
// hosts use the generated alias written by WriteSSHConfig.
func (h Host) Alias() string {
	if h.FromSSHConfig {
		return h.Name
	}
	return generatedAliasPrefix + h.Name
}

// Find resolves a host by name or alias.
func Find(hosts []Host, name string) (Host, bool) {
	for _, host := range hosts {
		if host.Name == name || host.Alias() == name {
			return host, true
		}
	}
	return Host{}, false
}

// Address is a parsed host target: [user@]host[:port] or ssh://user@host:port.
type Address struct {
	User string
	Host string
	Port string
}

// ParseAddress parses a configured host target. Values are validated so they
// can be interpolated into ssh_config without quoting: no whitespace, no
// control characters, and only characters that are meaningful in a hostname,
// username, or port.
func ParseAddress(raw string) (Address, error) {
	if raw == "" {
		return Address{}, errors.New("target is required")
	}
	if raw != strings.TrimSpace(raw) {
		return Address{}, errors.New("target must not contain surrounding whitespace")
	}
	if err := validateNoControl(raw); err != nil {
		return Address{}, err
	}
	if strings.HasPrefix(raw, "-") {
		return Address{}, errors.New(`target must not start with "-"`)
	}
	var address Address
	rest := raw
	if scheme, ok := strings.CutPrefix(raw, "ssh://"); ok {
		parsed, err := url.Parse("ssh://" + scheme)
		if err != nil {
			return Address{}, fmt.Errorf("invalid target %q: %w", raw, err)
		}
		if parsed.Path != "" || parsed.RawQuery != "" || parsed.Fragment != "" {
			return Address{}, fmt.Errorf("invalid target %q: expected ssh://user@host:port", raw)
		}
		if parsed.User != nil {
			address.User = parsed.User.Username()
		}
		address.Host = parsed.Hostname()
		address.Port = parsed.Port()
	} else {
		if user, host, ok := strings.Cut(rest, "@"); ok {
			address.User, rest = user, host
		}
		switch {
		case strings.HasPrefix(rest, "["):
			end := strings.Index(rest, "]")
			if end < 0 {
				return Address{}, fmt.Errorf("invalid target %q: unterminated [address]", raw)
			}
			address.Host = rest[1:end]
			if tail := rest[end+1:]; tail != "" {
				if !strings.HasPrefix(tail, ":") {
					return Address{}, fmt.Errorf("invalid target %q", raw)
				}
				address.Port = strings.TrimPrefix(tail, ":")
			}
		case strings.Contains(rest, ":"):
			address.Host, address.Port, _ = strings.Cut(rest, ":")
		default:
			address.Host = rest
		}
	}
	if err := validateAddress(address); err != nil {
		return Address{}, fmt.Errorf("invalid target %q: %w", raw, err)
	}
	return address, nil
}

func validateAddress(address Address) error {
	if address.Host == "" {
		return errors.New("target host is required")
	}
	if strings.HasPrefix(address.Host, "-") {
		return errors.New(`target host must not start with "-"`)
	}
	for _, r := range address.Host {
		if !hostCharOK(r) {
			return fmt.Errorf("target host contains an unsupported character %q", r)
		}
	}
	if address.User != "" {
		for _, r := range address.User {
			if !userCharOK(r) {
				return fmt.Errorf("target user contains an unsupported character %q", r)
			}
		}
	}
	if address.Port != "" {
		port := 0
		for _, r := range address.Port {
			if r < '0' || r > '9' {
				return fmt.Errorf("target port %q is not numeric", address.Port)
			}
			port = port*10 + int(r-'0')
		}
		if port < 1 || port > 65535 {
			return fmt.Errorf("target port %q is out of range", address.Port)
		}
	}
	return nil
}

func hostCharOK(r rune) bool {
	if isAlnum(r) {
		return true
	}
	switch r {
	// ":" keeps bare IPv6 literals usable; "%" covers IPv6 zone ids.
	case '.', '-', '_', ':', '%', '[', ']':
		return true
	}
	return false
}

func userCharOK(r rune) bool {
	if isAlnum(r) {
		return true
	}
	switch r {
	case '.', '-', '_', '+':
		return true
	}
	return false
}

func isAlnum(r rune) bool {
	return r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9'
}

func validateNoControl(value string) error {
	for _, r := range value {
		if r < 0x20 || r == 0x7f {
			return errors.New("must not contain control characters")
		}
	}
	return nil
}

// RenderSSHConfig renders the generated ssh config: one Host block per
// configured host, in config order. Hosts discovered from the user's
// ~/.ssh/config are skipped because they are already defined there.
func RenderSSHConfig(hosts []Host) (string, error) {
	var b strings.Builder
	b.WriteString(sshConfigHeader + "\n")
	for _, host := range hosts {
		if host.FromSSHConfig {
			continue
		}
		block, err := renderHostBlock(host)
		if err != nil {
			return "", err
		}
		b.WriteString("\n" + block)
	}
	return b.String(), nil
}

func renderHostBlock(host Host) (string, error) {
	if err := validateHostName(host.Name); err != nil {
		return "", fmt.Errorf("host %q: %w", host.Name, err)
	}
	address, err := ParseAddress(host.Target)
	if err != nil {
		return "", fmt.Errorf("host %q: %w", host.Name, err)
	}
	proxy := strings.TrimSpace(host.ProxyCommand)
	if proxy != "" {
		if err := validateNoControl(proxy); err != nil {
			return "", fmt.Errorf("host %q: proxy_command %w", host.Name, err)
		}
	}
	if host.Transport == TransportIroh {
		// iroh-ssh is a ProxyCommand transport: the target is the endpoint id,
		// and %h expands to the HostName above.
		proxy = "iroh-ssh proxy %h"
	}
	lines := []string{"Host " + host.Alias(), "  HostName " + address.Host}
	if address.User != "" {
		lines = append(lines, "  User "+address.User)
	}
	if address.Port != "" {
		lines = append(lines, "  Port "+address.Port)
	}
	if proxy != "" {
		lines = append(lines, "  ProxyCommand "+proxy)
	}
	return strings.Join(lines, "\n") + "\n", nil
}

// validateHostName checks the [A-Za-z0-9._-]+ charset seshagy requires for
// configured host names (it is also the ssh alias suffix).
func validateHostName(name string) error {
	if name == "" {
		return errors.New("name is required")
	}
	if strings.HasPrefix(name, "-") {
		return errors.New(`name must not start with "-"`)
	}
	for _, r := range name {
		if !isAlnum(r) && r != '.' && r != '_' && r != '-' {
			return fmt.Errorf("name %q may only contain [A-Za-z0-9._-]", name)
		}
	}
	return nil
}

// SSHConfigPath returns the path of the generated ssh config.
func SSHConfigPath() string {
	return filepath.Join(xdg.ConfigHome(), "seshagy", "ssh_config")
}

// userSSHConfigPath returns ~/.ssh/config.
func userSSHConfigPath() string {
	return filepath.Join(xdg.Home(), ".ssh", "config")
}

// UserSSHConfigPath returns the path of the user's ssh config.
func UserSSHConfigPath() string { return userSSHConfigPath() }

// WriteSSHConfig writes the generated ssh config (0600, parent dir 0700) and
// reports whether the content changed. Unchanged content is left untouched so
// the file is not rewritten on every launcher start.
func WriteSSHConfig(hosts []Host) (bool, error) {
	content, err := RenderSSHConfig(hosts)
	if err != nil {
		return false, err
	}
	path := SSHConfigPath()
	if existing, err := os.ReadFile(path); err == nil && string(existing) == content {
		return false, nil
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return false, fmt.Errorf("create %s: %w", dir, err)
	}
	tmp, err := os.CreateTemp(dir, ".ssh_config-*")
	if err != nil {
		return false, fmt.Errorf("create temp ssh config: %w", err)
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()
	if _, err := tmp.WriteString(content); err != nil {
		_ = tmp.Close()
		return false, fmt.Errorf("write temp ssh config: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return false, fmt.Errorf("close temp ssh config: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return false, fmt.Errorf("replace %s: %w", path, err)
	}
	return true, nil
}

// IncludeLine is the line users add to ~/.ssh/config so OpenSSH (and therefore
// herdr) picks up the generated config.
func IncludeLine() string {
	return "Include " + xdg.ContractHome(SSHConfigPath())
}

// IncludeIsSetup reports whether the generated ssh config is already included by
// ~/.ssh/config, i.e. whether `seshagy hosts setup` has run.
func IncludeIsSetup() bool {
	ok, err := UserSSHConfigHasInclude()
	return err == nil && ok
}

// UserSSHConfigHasInclude reports whether ~/.ssh/config Includes the generated
// config. A missing ~/.ssh/config is not an error.
func UserSSHConfigHasInclude() (bool, error) {
	path := userSSHConfigPath()
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return includesPath(string(data), filepath.Dir(path), SSHConfigPath()), nil
}

// EnsureUserSSHConfigInclude prepends the Include line to ~/.ssh/config,
// creating the file (0600) and its directory when needed. The user's content is
// preserved and backed up once to ~/.ssh/config.seshagy.bak. It only runs from
// the explicit `seshagy hosts setup` command.
func EnsureUserSSHConfigInclude() (bool, error) {
	has, err := UserSSHConfigHasInclude()
	if err != nil {
		return false, err
	}
	if has {
		return false, nil
	}
	path := userSSHConfigPath()
	existing, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	if len(existing) > 0 {
		if err := backupOnce(path, existing); err != nil {
			return false, err
		}
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return false, fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	content := IncludeLine() + "\n"
	if len(existing) > 0 {
		content += "\n" + string(existing)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		return false, fmt.Errorf("write %s: %w", path, err)
	}
	return true, nil
}

func backupOnce(path string, content []byte) error {
	backup := path + ".seshagy.bak"
	if _, err := os.Stat(backup); err == nil {
		return nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.WriteFile(backup, content, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", backup, err)
	}
	return nil
}

// DiscoverSSHConfigHosts lists the non-wildcard Host patterns of path and of
// the files it Includes (one level, glob-expanded). Seshagy's own generated
// aliases are skipped so they are never offered as user hosts.
func DiscoverSSHConfigHosts(path string) ([]Host, error) {
	files := []string{path}
	data, err := os.ReadFile(path)
	if err != nil {
		if !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
	} else {
		files = append(files, includeFiles(string(data), filepath.Dir(path))...)
	}
	var hosts []Host
	seen := map[string]bool{}
	for _, file := range files {
		content, err := os.ReadFile(file)
		if err != nil {
			continue
		}
		for _, name := range hostPatterns(string(content)) {
			if seen[name] || !usableHostPattern(name) {
				continue
			}
			seen[name] = true
			hosts = append(hosts, Host{
				Name: name, Target: name, Transport: TransportSSH, FromSSHConfig: true,
			})
		}
	}
	return hosts, nil
}

// Hosts merges configured hosts (first, in config order) with the hosts
// discovered from ~/.ssh/config when discover is set, deduplicating by alias.
func Hosts(configured []Host, discover bool) []Host {
	out := make([]Host, 0, len(configured))
	seen := map[string]bool{}
	add := func(host Host) {
		alias := host.Alias()
		if alias == "" || seen[alias] {
			return
		}
		seen[alias] = true
		out = append(out, host)
	}
	for _, host := range configured {
		add(host)
	}
	if discover {
		discovered, err := DiscoverSSHConfigHosts(userSSHConfigPath())
		if err == nil {
			for _, host := range discovered {
				add(host)
			}
		}
	}
	return out
}

// usableHostPattern reports whether a discovered ssh_config Host pattern can be
// offered as a remote: wildcard and negated patterns cannot be addressed,
// seshagy's own generated aliases already exist in the generated config, and a
// leading "-" or a control character would make ssh/herdr read the alias as an
// option rather than a host.
func usableHostPattern(name string) bool {
	if name == "" || strings.HasPrefix(name, generatedAliasPrefix) {
		return false
	}
	if strings.HasPrefix(name, "-") || strings.ContainsAny(name, "*?!") {
		return false
	}
	return validateNoControl(name) == nil
}

func hostPatterns(content string) []string {
	var out []string
	for _, line := range strings.Split(content, "\n") {
		keyword, value := splitConfigLine(line)
		if keyword != "host" {
			continue
		}
		out = append(out, strings.Fields(value)...)
	}
	return out
}

func includeFiles(content, dir string) []string {
	var out []string
	for _, line := range strings.Split(content, "\n") {
		keyword, value := splitConfigLine(line)
		if keyword != "include" {
			continue
		}
		for _, arg := range strings.Fields(value) {
			matches, err := filepath.Glob(resolveIncludePath(arg, dir))
			if err != nil {
				continue
			}
			out = append(out, matches...)
		}
	}
	return out
}

func includesPath(content, dir, want string) bool {
	want = filepath.Clean(want)
	for _, line := range strings.Split(content, "\n") {
		keyword, value := splitConfigLine(line)
		if keyword != "include" {
			continue
		}
		for _, arg := range strings.Fields(value) {
			if filepath.Clean(resolveIncludePath(arg, dir)) == want {
				return true
			}
		}
	}
	return false
}

func resolveIncludePath(arg, dir string) string {
	path := xdg.ExpandHome(arg)
	if !filepath.IsAbs(path) {
		path = filepath.Join(dir, path)
	}
	return path
}

// splitConfigLine splits an ssh_config line into a lowercase keyword and its
// value, dropping comments and tolerating the `Keyword=value` form.
func splitConfigLine(line string) (string, string) {
	if i := strings.IndexByte(line, '#'); i >= 0 {
		line = line[:i]
	}
	line = strings.TrimSpace(strings.Replace(line, "=", " ", 1))
	if i := strings.IndexFunc(line, unicode.IsSpace); i >= 0 {
		return strings.ToLower(line[:i]), strings.TrimSpace(line[i:])
	}
	return strings.ToLower(line), ""
}
